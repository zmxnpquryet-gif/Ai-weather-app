    fun findById(id: String?): AtmosphericThemeSpec {
        if (id.isNullOrBlank()) return allThemes.first()
        return allThemes.find { it.id.equals(id.trim(), ignoreCase = true) } ?: allThemes.first()
    }

    fun selectBestThemeForWeather(
        weatherCode: Int,
        tempC: Double,
        isDay: Boolean,
        pm10: Double,
        pm25: Double,
        windSpeedMs: Double,
        uvIndex: Double
    ): AtmosphericThemeSpec {
        if (pm10 > 150) return findById("YELLOW_DUST_DESERT_WIND")
        if (pm10 > 80 || pm25 > 35) return findById("FINE_DUST_AMBER_ALERT")
        if (!isDay && weatherCode in listOf(0, 1, 2)) return findById("STARRY_CLEAR_NIGHT")
        if (weatherCode in listOf(71, 73, 75, 77, 85, 86)) {
            return if (weatherCode == 71) findById("FIRST_SNOW_ROMANCE") else findById("WINTER_SNOW_MOUNTAIN")
        }
        if (weatherCode in listOf(95, 96, 99)) return findById("THUNDER_LIGHTNING_STORM")
        if (weatherCode in listOf(51, 53, 55, 56, 57)) return findById("LIGHT_DRIZZLE_WINDOW")
        if (weatherCode in listOf(80, 81, 82)) return findById("SUMMER_SHOWER_RAINBOW")
        if (weatherCode in listOf(61, 63, 65, 66, 67)) {
            return if (weatherCode == 65 || windSpeedMs >= 7.0) findById("HEAVY_MONSOON_RAIN") else findById("RAIN_UMBRELLA_CITY")
        }
        if (weatherCode in listOf(45, 48)) return findById("MISTY_LAKE_DAWN")
        if (windSpeedMs >= 8.0) return findById("GALE_WIND_WARNING")
        if (weatherCode == 3) {
            return if (tempC in 10.0..20.0) findById("AUTUMN_MAPLE_CLOUD") else findById("OVERCAST_CALM_CAFE")
        }
        if (weatherCode == 2) {
            return if (tempC in 12.0..21.0) findById("AUTUMN_MAPLE_CLOUD") else findById("SOFT_CLOUD_COTTON")
        }
        return when {
            tempC <= -2.0 -> findById("ARCTIC_COLD_WAVE")
            tempC <= 6.0 -> findById("WINTER_CLEAR_SUNSHINE")
            tempC <= 13.0 -> findById("CHILLY_MORNING_COAT")
            tempC in 13.1..21.5 -> findById("SPRING_CHERRY_SKY")
            tempC in 21.6..26.5 -> findById("EARLY_SUMMER_GREEN")
            tempC > 30.0 || uvIndex >= 8.0 -> findById("TROPICAL_HEATWAVE_SUN")
            else -> findById("MIDSUMMER_OCEAN_BLUE")
        }
    }
